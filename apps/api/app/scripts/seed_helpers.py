"""Safe synthetic values shared by development-only seed scripts."""

from __future__ import annotations

import asyncio
import uuid
from typing import Any

from pydantic import EmailStr, TypeAdapter, ValidationError
from sqlalchemy.ext.asyncio import AsyncSession

_email_adapter = TypeAdapter(EmailStr)


def dev_indian_mobile() -> str:
    """Return a synthetic ten-digit Indian mobile number in E.164 format."""
    local_number = uuid.uuid4().int % 4_000_000_000 + 6_000_000_000
    return f"+91{local_number}"


def dev_seed_email(value: str) -> str:
    """Normalize an email accepted by the application response contract."""
    try:
        return str(_email_adapter.validate_python(value))
    except ValidationError as exc:
        raise ValueError("Email must be a valid, non-reserved address.") from exc


def require_development(script: str) -> None:
    """Refuse to run a development seeder against any other environment."""
    from app.core.config import settings

    if settings.ENV != "development":
        raise SystemExit(
            f"{script} is development-only; refusing to run with ENV={settings.ENV!r}."
        )


async def add_once(db: AsyncSession, row: Any) -> bool:
    """Add ``row`` unless a row with the same primary key already exists."""
    existing = await db.get(type(row), row.id)
    if existing is not None:
        return False
    db.add(row)
    return True


async def put_once(object_key: str, content: bytes, content_type: str) -> None:
    """Write generated bytes unless an identical-size object is already there."""
    from app.services import storage

    if await asyncio.to_thread(storage.head_object, object_key) != len(content):
        await asyncio.to_thread(storage.put_object_bytes, object_key, content, content_type)
