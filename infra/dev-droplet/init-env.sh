#!/usr/bin/env bash
# Write the repository-root .env for the development droplet with fresh,
# random credentials. Run once per fresh droplet; it never overwrites.
set -Eeuo pipefail

usage() {
  cat >&2 <<'EOF'
usage: infra/dev-droplet/init-env.sh --domain HOST \
         --allow-ip IP_OR_CIDR [--allow-ip IP_OR_CIDR ...]

Writes ./.env (mode 600) with fresh secrets and creates an empty
apps/api/.env.local if missing. Refuses to overwrite an existing .env.
EOF
  exit 2
}

fail() {
  echo "init-env: $*" >&2
  exit 1
}

domain=""
allowed=()

while (($#)); do
  case $1 in
    --domain | --allow-ip)
      (($# >= 2)) || usage
      case $1 in
        --domain) domain=$2 ;;
        --allow-ip) allowed+=("$2") ;;
      esac
      shift 2
      ;;
    *) usage ;;
  esac
done

[[ -n $domain && ${#allowed[@]} -gt 0 ]] || usage

host_re='^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$'
cidr_re='^(([0-9]{1,3}\.){3}[0-9]{1,3}(/[0-9]{1,2})?|[0-9a-f:]*:[0-9a-f:]*(/[0-9]{1,3})?)$'

[[ $domain =~ $host_re ]] || fail "--domain must be a lowercase hostname"
for ip in "${allowed[@]}"; do
  [[ $ip =~ $cidr_re ]] || fail "--allow-ip '$ip' is not an IP address or CIDR"
  # An allow-all range would silently remove the only access control.
  case $ip in
    */0 | 0.0.0.0* | ::) fail "--allow-ip '$ip' would allow everyone" ;;
  esac
done

command -v openssl >/dev/null 2>&1 || fail "openssl is required"

root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)
env_file="$root/.env"

# The Postgres password is fixed when its volume is first created, so a second
# run would desynchronise credentials from existing data.
[[ ! -e $env_file ]] || fail ".env already exists; it is bound to the existing volumes. Remove it only together with '$root/infra/dev-droplet/dc.sh down -v'."

secret() { openssl rand -hex "$1"; }

umask 077
tmp=$(mktemp "$root/.env.tmp.XXXXXX")
trap 'rm -f "$tmp"' EXIT
cat >"$tmp" <<EOF
# Generated by infra/dev-droplet/init-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ).
# Development droplet only. Never commit or copy this file.
DEV_DOMAIN=$domain
DEV_ALLOWED_IPS="${allowed[*]}"
POSTGRES_DB=app
POSTGRES_USER=app
POSTGRES_PASSWORD=$(secret 32)
DEV_SECRET_KEY=$(secret 32)
EOF
mv "$tmp" "$env_file"
trap - EXIT

# docker-compose.yml requires this file; compose environment overrides the
# keys above, so it only holds optional settings such as SMTP.
api_env="$root/apps/api/.env.local"
[[ -e $api_env ]] || : >"$api_env"

echo "Wrote $env_file with fresh credentials."
echo "Next: append the dev Space's SPACES_* block to $env_file by hand (README step 4b)."
